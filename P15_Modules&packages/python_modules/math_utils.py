def add(a, b):
    """Returns the sum of a and b."""
    return a + b

def subtract(a, b):
    """Returns the difference of a and b."""
    return a - b

PI = 3.14159

if __name__ == "__main__":
    print("Running math_utils.py directly")
    print("add(2, 3) =", add(2, 3))
    print("subtract(5, 2) =", subtract(5, 2))
    print(f"Value of PI: {PI}")